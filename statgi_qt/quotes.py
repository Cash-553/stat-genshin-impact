def pick(n=1):
    """随机挑 n 条（不重复），返回 [(正文, 署名), ...]"""
    import random
    n = max(1, int(n))
    if n >= len(QUOTES):
        out = list(QUOTES)
        random.shuffle(out)
        return out
    return random.sample(QUOTES, n)
